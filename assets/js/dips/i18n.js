const DICTS = { en, de };

function readStored() {
  try { const v = localStorage.getItem(STORE_KEY); return v === "de" || v === "en" ? v : null; } catch (e) { return null; }
}

let lang = readStored() || ((navigator.language || "").toLowerCase().startsWith("de") ? "de" : "en");

export function getLang() { return lang; }

export function setLang(next) {
  lang = next === "de" ? "de" : "en";
  try { localStorage.setItem(STORE_KEY, lang); } catch (e) { /* storage unavailable: keep for this visit */ }
  document.documentElement.lang = lang;
}

/** Locale for Intl formatting. */
export const locale = () => (lang === "de" ? "de-DE" : "en-GB");

export function t(key, params = {}) {
  const raw = (DICTS[lang] && DICTS[lang][key]) || en[key] || key;
  return raw.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** Translate static markup: data-i18n (text), data-i18n-placeholder, data-i18n-aria-label, data-i18n-title. */
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel)); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}

